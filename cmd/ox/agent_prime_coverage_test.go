func TestIsAutoGeneratedAgentsMD_Coverage(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name    string
		content string
		want    bool
	}{
		{
			name:    "auto-generated boilerplate",
			content: "# Agents\n\n*Generated by SageOx CLI* - do not edit\n\nSome content",
			want:    true,
		},
		{
			name:    "hand-authored content",
			content: "# Team Conventions\n\nUse Go 1.21 or later.\n",
			want:    false,
		},
		{
			name:    "empty content",
			content: "",
			want:    false,
		},
		{
			name:    "partial match substring",
			content: "This mentions Generated by SageOx but is not the marker",
			want:    false,
		},
		{
			name:    "exact marker with asterisk",
			content: "*Generated by SageOx CLI",
			want:    true,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			got := isAutoGeneratedAgentsMD(tt.content)
			if got != tt.want {
				t.Errorf("isAutoGeneratedAgentsMD(%q) = %v, want %v", tt.content, got, tt.want)
			}
		})
	}
}

