func TestDiscoverMemoryFiles(t *testing.T) {
	t.Parallel()

	t.Run("nonexistent directory", func(t *testing.T) {
		t.Parallel()
		files := discoverMemoryFiles("/nonexistent/path")
		if files != nil {
			t.Errorf("expected nil for nonexistent dir, got %v", files)
		}
	})

	t.Run("empty directory", func(t *testing.T) {
		t.Parallel()
		dir := t.TempDir()
		files := discoverMemoryFiles(dir)
		if files != nil {
			t.Errorf("expected nil for empty dir, got %v", files)
		}
	})

	t.Run("only non-md files", func(t *testing.T) {
		t.Parallel()
		dir := t.TempDir()
		os.WriteFile(filepath.Join(dir, "notes.txt"), []byte("text"), 0644)
		os.WriteFile(filepath.Join(dir, "data.json"), []byte("{}"), 0644)
		files := discoverMemoryFiles(dir)
		if files != nil {
			t.Errorf("expected nil when no .md files, got %v", files)
		}
	})

	t.Run("md files sorted reverse chronologically", func(t *testing.T) {
		t.Parallel()
		dir := t.TempDir()
		os.WriteFile(filepath.Join(dir, "2024-01-01.md"), []byte("jan"), 0644)
		os.WriteFile(filepath.Join(dir, "2024-03-15.md"), []byte("mar"), 0644)
		os.WriteFile(filepath.Join(dir, "2024-02-10.md"), []byte("feb"), 0644)

		files := discoverMemoryFiles(dir)
		if len(files) != 3 {
			t.Fatalf("expected 3 files, got %d", len(files))
		}
		// reverse chronological: newest first
		if files[0] != "2024-03-15.md" {
			t.Errorf("files[0] = %q, want %q", files[0], "2024-03-15.md")
		}
		if files[1] != "2024-02-10.md" {
			t.Errorf("files[1] = %q, want %q", files[1], "2024-02-10.md")
		}
		if files[2] != "2024-01-01.md" {
			t.Errorf("files[2] = %q, want %q", files[2], "2024-01-01.md")
		}
	})

	t.Run("skips directories", func(t *testing.T) {
		t.Parallel()
		dir := t.TempDir()
		os.WriteFile(filepath.Join(dir, "note.md"), []byte("x"), 0644)
		os.MkdirAll(filepath.Join(dir, "subdir.md"), 0755) // directory with .md name
		files := discoverMemoryFiles(dir)
		if len(files) != 1 {
			t.Fatalf("expected 1 file, got %d: %v", len(files), files)
		}
		if files[0] != "note.md" {
			t.Errorf("files[0] = %q, want %q", files[0], "note.md")
		}
	})
}

